KEY_RE = re.compile(r'\bLF?\("((?:[^"\\]|\\.)*)"')


def collect():
    keys = set()
    for dirpath, _, files in os.walk(SRC):
        for f in files:
            if f.endswith(".swift"):
                keys.update(KEY_RE.findall(open(os.path.join(dirpath, f), encoding="utf-8").read()))
    return sorted(keys)


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def write(lang, table, keys):
    folder = os.path.join(SRC, "Resources", f"{lang}.lproj")
    os.makedirs(folder, exist_ok=True)
    with open(os.path.join(folder, "Localizable.strings"), "w", encoding="utf-8") as fh:
        fh.write("/* Generated by scripts/l10n.py */\n\n")
        for k in keys:
            raw = k.encode().decode("unicode_escape") if "\\" in k else k
            fh.write(f'"{esc(raw)}" = "{esc(table.get(raw, EN.get(raw, raw)))}";\n')


keys = collect()
write("en", EN, keys)
write("vi", VI, keys)
missing = [k for k in keys if k not in VI]
print(f"{len(keys)} keys, {len(missing)} missing vi:")
for k in missing:
    print("  ", k)
